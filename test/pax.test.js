import { assert, test } from 'ubqtest'
import { Pax } from '../src/pax.js'

// A Pax object with the given fields set, and each other field unset.
const pax = fields =>
  Object.assign(Object.create(Pax.prototype), {
    atime: undefined,
    charset: undefined,
    comment: undefined,
    ctime: undefined,
    dev: undefined,
    gid: undefined,
    global: false,
    gname: undefined,
    ino: undefined,
    linkpath: undefined,
    mode: undefined,
    mtime: undefined,
    nlink: undefined,
    path: undefined,
    size: undefined,
    uid: undefined,
    uname: undefined,
    ...fields,
  })

