import { any, assert, test } from 'ubqtest'
import * as tar from '../src/index.js'

test('index exports the public API', () => {
  assert.match(tar, {
    create: any.function,
    c: any.function,
    replace: any.function,
    r: any.function,
    list: any.function,
    t: any.function,
    update: any.function,
    u: any.function,
    extract: any.function,
    x: any.function,
    Pack: any.function,
    Unpack: any.function,
    Parser: any.function,
    ReadEntry: any.function,
    WriteEntry: any.function,
    Header: any.function,
    Pax: any.function,
    types: {
      name: new Map([
        ['0', 'File'],
        ['', 'OldFile'],
        ['1', 'Link'],
        ['2', 'SymbolicLink'],
        ['3', 'CharacterDevice'],
        ['4', 'BlockDevice'],
        ['5', 'Directory'],
        ['6', 'FIFO'],
        ['7', 'ContiguousFile'],
        ['g', 'GlobalExtendedHeader'],
        ['x', 'ExtendedHeader'],
        ['A', 'SolarisACL'],
        ['D', 'GNUDumpDir'],
        ['I', 'Inode'],
        ['K', 'NextFileHasLongLinkpath'],
        ['L', 'NextFileHasLongPath'],
        ['M', 'ContinuationFile'],
        ['N', 'OldGnuLongPath'],
        ['S', 'SparseFile'],
        ['V', 'TapeVolumeHeader'],
        ['X', 'OldExtendedHeader'],
      ]),
      code: new Map([
        ['File', '0'],
        ['OldFile', ''],
        ['Link', '1'],
        ['SymbolicLink', '2'],
        ['CharacterDevice', '3'],
        ['BlockDevice', '4'],
        ['Directory', '5'],
        ['FIFO', '6'],
        ['ContiguousFile', '7'],
        ['GlobalExtendedHeader', 'g'],
        ['ExtendedHeader', 'x'],
        ['SolarisACL', 'A'],
        ['GNUDumpDir', 'D'],
        ['Inode', 'I'],
        ['NextFileHasLongLinkpath', 'K'],
        ['NextFileHasLongPath', 'L'],
        ['ContinuationFile', 'M'],
        ['OldGnuLongPath', 'N'],
        ['SparseFile', 'S'],
        ['TapeVolumeHeader', 'V'],
        ['OldExtendedHeader', 'X'],
      ]),
    },
  })
  assert.match(tar.PackSync, any.function)
  assert.match(tar.WriteEntrySync, any.function)
  assert.match(tar.WriteEntryTar, any.function)
  assert.match(tar.Pax.parse, any.function)
})
